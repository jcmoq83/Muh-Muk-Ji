def render_cards(items: list[tuple[str, str, str]]) -> str:
    cards = []
    for title, href, text in items:
        cards.append(
            f'<a class="listing-card" href="{href}"><h3>{title}</h3><p>{text}</p><span class="card-cta">자세히 보기</span></a>'
        )
    return '<div class="listing-grid">' + "".join(cards) + "</div>"


