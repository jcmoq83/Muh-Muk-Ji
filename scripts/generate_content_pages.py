def breadcrumbs(items: list[tuple[str, str]]) -> str:
    parts = ['<nav class="breadcrumbs" aria-label="breadcrumb">']
    for idx, (label, href) in enumerate(items):
        if idx == len(items) - 1:
            parts.append(f'<span aria-current="page">{label}</span>')
        else:
            parts.append(f'<a href="{href}">{label}</a><span class="crumb-sep">/</span>')
    parts.append("</nav>")
    return "".join(parts)


def schema_for_page(page_url: str, title: str, description: str, crumbs: list[tuple[str, str]], article: bool = False) -> str:
    website = {
        "@context": "https://schema.org",
        "@type": "WebSite",
        "name": "머먹지!?",
        "url": f"{DOMAIN}/",
        "description": "오늘 먹을 메뉴를 빠르게 고를 수 있는 메뉴 토너먼트 서비스",
    }
    breadcrumb = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {
                "@type": "ListItem",
                "position": idx + 1,
                "name": label,
                "item": build_url(href),
            }
            for idx, (label, href) in enumerate(crumbs)
        ],
    }
    schemas = [website, breadcrumb]
    if article:
        schemas.append(
            {
                "@context": "https://schema.org",
                "@type": "Article",
                "headline": title,
                "description": description,
                "author": {"@type": "Person", "name": "JC Won"},
                "datePublished": UPDATED_AT,
                "dateModified": UPDATED_AT,
                "mainEntityOfPage": build_url(page_url),
            }
        )
    return '<script type="application/ld+json">' + json.dumps(schemas, ensure_ascii=False) + "</script>"


