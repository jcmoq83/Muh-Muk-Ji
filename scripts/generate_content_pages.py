def has_batchim(text: str) -> bool:
    if not text:
        return False
    ch = text[-1]
    code = ord(ch) - 0xAC00
    if code < 0 or code > 11171:
        return False
    return code % 28 != 0


def topic(text: str) -> str:
    return f"{text}{'은' if has_batchim(text) else '는'}"


def with_particle(text: str) -> str:
    return f"{text}{'과' if has_batchim(text) else '와'}"


